import java.util.Locale

/** Supported in-app languages. SYSTEM follows the device locale (Polish -> PL, otherwise EN). */
enum class Language(val code: String) {
    SYSTEM("system"),
    EN("en"),
    PL("pl");

    companion object {
        fun fromCode(code: String?): Language = entries.firstOrNull { it.code == code } ?: SYSTEM
        fun resolve(setting: Language): Language = when (setting) {
            SYSTEM -> if (Locale.getDefault().language == "pl") PL else EN
            else -> setting
        }
    }
}

